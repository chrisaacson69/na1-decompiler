"""na1_regen.py - regenerate NA1's bytecode source tiers from the shared engine (emu-harness).

The walks' apply steps (label-walk-apply, var-walk-apply) regenerate after writing names, then guard
the diff. They used to run tools/decompile-all.py, which the graduation to the shared engine removed,
so a batch could not complete. This is source/README.md's recipe, for every bytecode bank, so the
guard also sees a name that leaks into ANOTHER bank:

  2-asm-vm/bank_NN_vm.asm   disasm na1 N
  4-c/bank_NN.c             decompile na1 N        (structured)
  3-c-basic/bank_NN.raw.c   decompile na1 N --raw  (goto form)

One process per step: the decompiler keeps its structuring switches in module globals, so a raw run
would leave later banks unstructured. Needs py -3.14 with emu-harness installed.
A full regen also re-keys the merged views (4-c/all_banks.c, 3-c-basic/all_banks.raw.c) from the
per-bank C just written, through emu-harness cli/decompile_merged, and rewrites the raw 6502 rung,
1-asm-6502/bank_NN.asm for all 16 banks: the linear force-decode of emu-harness cpu.m6502.disasm.render
(bank 15 at $C000, the others at $8000), which reproduced the committed files byte for byte (2026-10-30).
The labeled 6502 listings are mesen-labels.py --asm's.
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "source"
BANKS = (0, 1, 2, 10, 14, 15)


BANNER = """// ============================================================
// source/{rel}  --  GENERATED by tools/na1_regen.py (emu-harness vm.koei.nes engine)
// bytecode bank {bank} of Nobunaga's Ambition (USA).nes. Symbols: ../../mesen-labels.toml. Regen: source/README.md
// Deterministic (fixed ROM + toml -> identical output). DO NOT hand-edit -- regenerate.
// Pipeline: titles disasm -> vm_decompile{raw}
// ============================================================
"""


def regen(banks=BANKS):
    """Regenerate every tier of `banks`; -> [] or the failing steps' messages.

    Paths go to the engine project-relative (run from the project root): it prints the path it is given on
    every sub's `// Decompiled from` line, so an absolute path would put this machine's layout into
    committed files and make the output differ per machine. The banner is ours; the engine writes none."""
    errs = []
    for b in banks:
        bb = f"{b:02d}"
        asm = f"source/2-asm-vm/bank_{bb}_vm.asm"
        outs = {f"source/4-c/bank_{bb}.c": [], f"source/3-c-basic/bank_{bb}.raw.c": ["--raw"]}
        # bank_NN_vm.asm is the decompiler's input (parse_listing reads it); bank_NN_vm_labeled.asm is the
        # reading view of the same walk (routine names, branch labels, address in the right margin)
        steps = ([["disasm", "na1", str(b), asm], ["disasm", "na1", str(b), f"source/2-asm-vm/bank_{bb}_vm_labeled.asm", "--labeled"]]
                 + [["decompile", "na1", str(b), asm, o, *x] for o, x in outs.items()])
        for args in steps:
            r = subprocess.run([sys.executable, "-m", "emu_harness.vm.koei.nes.titles", *args],
                               cwd=ROOT, capture_output=True, text=True)
            if r.returncode != 0:
                errs.append(f"{' '.join(args)}: {r.stdout[-400:]}{r.stderr[-400:]}")
        for o, x in outs.items():
            f = ROOT / o
            if f.exists():
                body = f.read_text(encoding="utf-8")
                head = BANNER.format(rel=o.split("source/", 1)[1], bank=b, raw="  (--raw: direct goto/label form, the structurer baseline)" if x else " -> DREAM structurer (V2 fallback)")
                f.write_text(head + body, encoding="utf-8")
    # the merged one-file views, re-keyed from the per-bank C just written (never decompiled separately)
    if set(banks) == set(BANKS):
        for out, src, pat in (("source/4-c/all_banks.c", "source/4-c", "bank_{bank:02d}.c"),
                              ("source/3-c-basic/all_banks.raw.c", "source/3-c-basic", "bank_{bank:02d}.raw.c")):
            r = subprocess.run([sys.executable, "-m", "emu_harness.vm.koei.nes.cli.decompile_merged",
                                "--out", out, "--source", src, "--pattern", pat], cwd=ROOT, capture_output=True, text=True)
            if r.returncode != 0:
                errs.append(f"decompile_merged {out}: {r.stdout[-400:]}{r.stderr[-400:]}")
        raw_6502()
    return errs


def raw_6502():
    """The force-decoded 6502 rung: every byte of every bank read as an instruction (the bytecode and
    data banks decode as garbage, which is the point). The ROM comes through the [na1] profile."""
    from emu_harness.cpu.m6502.disasm import render
    from emu_harness.vm.koei.nes import titles
    rom = Path(titles.game_cfg("na1")["_rom"]).read_bytes()
    for b in range(rom[4]):
        (SRC / "1-asm-6502" / f"bank_{b:02d}.asm").write_text(
            render(rom, b, base=0xC000 if b == rom[4] - 1 else 0x8000), encoding="utf-8")


if __name__ == "__main__":
    e = regen()
    print("\n".join(e) if e else f"regenerated banks {', '.join(map(str, BANKS))}")
    sys.exit(1 if e else 0)
